#시나리오: 회원 목록에서 나이/구매금액 조건에 맞는 회원만 뽑아 등급을 부여
#1. 구매금액이 100만원 이상이면 "VIP", 50만원 이상이면 "일반", 그 미만이면 "신규"로 등급을 매기는 함수 `get_grade(amount)`
#2. 회원 리스트를 순회하며 각 회원의 등급을 딕셔너리에 추가
#3. "VIP" 등급 회원만 따로 리스트로 출력

members = [
    {"이름": "김민준", "나이": 24, "구매금액": 320000},
    {"이름": "이서연", "나이": 31, "구매금액": 1250000},
    {"이름": "박지훈", "나이": 28, "구매금액": 780000},
    {"이름": "최유진", "나이": 42, "구매금액": 1800000},
    {"이름": "정현우", "나이": 19, "구매금액": 150000},
    {"이름": "강수빈", "나이": 35, "구매금액": 500000},
    {"이름": "윤도현", "나이": 47, "구매금액": 990000},
    {"이름": "한지민", "나이": 26, "구매금액": 2300000},
]
def get_grade(amount):
    if amount >= 1000000:
        return "VIP"
    elif amount >= 500000:
        return "일반"
    else:
        return "신규"

vip = []
for member in members:
    member["grade"] = get_grade(member["구매금액"])
    if member["grade"] == "VIP":
        vip.append(member)
for member in vip:
    print(member)
