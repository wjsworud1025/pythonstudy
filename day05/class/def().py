# 함수 관련 용어 정리
#
# 1. 함수 호출
#    함수를 사용하는 것을 함수 호출이라고 한다.
#    예: len("안녕하세요")
#
# 2. 매개변수
#    함수를 호출할 때 괄호 안에 넣는 자료를 매개변수라고 한다.
#    len() 함수에 전달한 "안녕하세요"가 매개변수이다.
#
# 3. 리턴값
#    함수를 호출한 뒤 최종적으로 나오는 결과를 리턴값이라고 한다.
#    len("안녕하세요")의 리턴값은 5이다.
#
# 매개변수 "안녕하세요" -> len() 함수 -> 리턴값 5

result = len("안녕하세요")
print(result)

